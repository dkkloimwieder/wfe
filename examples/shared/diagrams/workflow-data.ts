import type { DiagramEdge, DiagramNode } from '@wfe/components/diagram'

export function withWorkflowOutputs<N>(
  nodes: readonly DiagramNode<N>[],
  edges: readonly DiagramEdge<string>[],
): DiagramNode<N>[] {
  return nodes.map((node) => {
    const outputs = edges.filter((edge) => edge.source.node === node.id)
    return {
      ...node,
      height: node.height + outputs.length * 24 + (outputs.length ? 8 : 0),
      ports: outputs.map((edge, index) => ({
        id: edge.id,
        label: edge.label,
        side: 'right' as const,
        offset: node.height + index * 24 + 12,
        showLabel: true,
      })),
    }
  })
}

