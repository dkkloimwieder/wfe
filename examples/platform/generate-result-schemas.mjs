import { readFile, readdir, writeFile } from 'node:fs/promises'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { format } from 'prettier'
import * as z from 'zod/mini'

const fieldMetadata = z.strictObject({
  path: z.string(),
  type: z.enum(['text', 'boolean', 'int32', 'uuid']),
  nullable: z.boolean(),
  values: z.array(z.union([z.string(), z.boolean(), z.number()])),
  label: z.optional(z.string()),
})
const resultMetadata = z.strictObject({
  class: z.literal('one'),
  fields: z.array(fieldMetadata),
})
const uuidPattern =
  /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i
const scalarSchemas = {
  text: z.string(),
  boolean: z.boolean(),
  int32: z.int32(),
  uuid: z.string().check(z.regex(uuidPattern)),
}
const scalarExpressions = {
  text: 'z.string()',
  boolean: 'z.boolean()',
  int32: 'z.int32()',
  uuid: `z.string().check(z.regex(${uuidPattern}))`,
}

/** Compile the captured subset: required objects/arrays and nullable scalar leaves. */
export function resultSchemaExpression(metadata) {
  const { fields } = resultMetadata.parse(metadata)
  const root = new Map()
  for (const field of fields) {
    const parts = field.path.split('.').map((part) => {
      const match = /^([A-Za-z_][A-Za-z0-9_]*)(\[\])?$/.exec(part)
      if (!match) throw new Error(`Unsupported result path: ${field.path}`)
      return { key: match[1], array: Boolean(match[2]) }
    })
    if (new Set(field.values).size !== field.values.length)
      throw new Error(`Repeated enum value: ${field.path}`)
    for (const value of field.values)
      if (!scalarSchemas[field.type].safeParse(value).success)
        throw new Error(`Invalid enum value: ${field.path}`)
    let children = root
    for (let i = 0; i < parts.length; i++) {
      const { key, array } = parts[i]
      let node = children.get(key)
      if (!node) {
        node = { array, children: new Map(), field: null }
        children.set(key, node)
      }
      if (node.array !== array || node.field)
        throw new Error(`Conflicting result path: ${field.path}`)
      if (i === parts.length - 1) {
        if (node.children.size)
          throw new Error(`Conflicting result path: ${field.path}`)
        node.field = field
      }
      children = node.children
    }
  }
  const object = (children) =>
    `z.object({${[...children]
      .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
      .map(([key, node]) => {
        let expression
        if (node.field) {
          const field = node.field
          expression = field.values.length
            ? `z.literal(${JSON.stringify(field.values)})`
            : scalarExpressions[field.type]
          if (field.nullable) expression = `z.nullable(${expression})`
        } else expression = object(node.children)
        if (node.array) expression = `z.array(${expression})`
        return `[${JSON.stringify(key)}]: ${expression}`
      })
      .join(',')}})`
  return object(root)
}

export async function generateResultSchemas() {
  let output = `// Generated by examples/platform/generate-result-schemas.mjs. Do not edit.\nimport * as z from 'zod/mini'\nimport type { ResultValidator } from './metadata-invoke'\n`
  for (const [namespace, directory] of [
    ['control', 'snapshot/metadata/'],
    ['application', 'snapshot/application/metadata/'],
  ]) {
    const root = new URL(directory, import.meta.url)
    const paths = []
    for (const group of (await readdir(root)).sort())
      for (const name of (await readdir(new URL(`${group}/`, root))).sort())
        if (name.endsWith('.result.json')) paths.push(`${group}/${name}`)
    const operations = new Set()
    const entries = []
    for (const path of paths) {
      const result = JSON.parse(await readFile(new URL(path, root), 'utf8'))
      const operation = JSON.parse(
        await readFile(
          new URL(path.replace('.result.json', '.operation.json'), root),
          'utf8',
        ),
      )
      if (
        typeof operation.operation !== 'string' ||
        !operation.operation.trim() ||
        operation.result !== result.class ||
        operations.has(operation.operation)
      )
        throw new Error(`Invalid or repeated operation: ${directory}${path}`)
      operations.add(operation.operation)
      entries.push(
        `// ${directory}${path}\n[${JSON.stringify(operation.operation)}, ${resultSchemaExpression(result)}]`,
      )
    }
    output += `export const ${namespace}ResultSchemas: ReadonlyMap<string, ResultValidator> = new Map<string, ResultValidator>([${entries.join(',')}])\n`
  }
  return format(output, {
    parser: 'typescript',
    semi: false,
    singleQuote: true,
    trailingComma: 'all',
  })
}

if (
  process.argv[1] &&
  import.meta.url === pathToFileURL(process.argv[1]).href
) {
  const path = new URL('result-schemas.generated.ts', import.meta.url)
  const generated = await generateResultSchemas()
  if (process.argv.includes('--check')) {
    if ((await readFile(path, 'utf8')) !== generated)
      throw new Error(
        'Platform result schemas differ from the captured metadata. Run node examples/platform/generate-result-schemas.mjs.',
      )
    console.log('Platform result schemas match the captured metadata.')
  } else {
    await writeFile(path, generated)
    console.log(`Generated ${fileURLToPath(path)}.`)
  }
}
