import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import * as prettier from 'prettier'
import {
  accents,
  paletteRoles,
  schemes,
  secondaryAccents,
} from '../packages/components/src/theme/palette.ts'
import { UI_DENSITIES } from '../packages/components/src/styles/density.ts'
import {
  tokenBlocks,
  tokenCss,
} from '../packages/components/src/theme/tokens.ts'

const destination = fileURLToPath(
  new URL('../packages/components/src/styles/tokens.css', import.meta.url),
)
const blocks = tokenBlocks({
  schemes,
  accents,
  secondaryAccents,
  roles: paletteRoles,
  densities: UI_DENSITIES,
})
const output = await prettier.format(
  [
    '/* Generated by scripts/theme-tokens.mjs. Edit theme/tokens.ts instead.',
    '   The token base: every --ui-* default, then one block per preset, mode,',
    '   density and application choice. Later blocks win. Zero specificity',
    '   leaves consumer classes and inline styles in control. */',
    '',
    tokenCss(blocks),
  ].join('\n'),
  {
    ...(await prettier.resolveConfig(destination)),
    filepath: destination,
  },
)

if (process.argv.includes('--check')) {
  if ((await readFile(destination, 'utf8')) !== output)
    throw new Error('Theme tokens are stale. Run node scripts/theme-tokens.mjs')
} else {
  await writeFile(destination, output)
}
