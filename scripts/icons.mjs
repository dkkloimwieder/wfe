import assert from 'node:assert/strict'
import { createHash } from 'node:crypto'
import { readFile, writeFile, rename } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { resolve } from 'node:path'
import { format } from 'prettier'

const tags = new Set([
  'path',
  'circle',
  'rect',
  'line',
  'ellipse',
  'polyline',
  'polygon',
])
const attributes = new Set([
  'd',
  'cx',
  'cy',
  'r',
  'rx',
  'ry',
  'x',
  'y',
  'x1',
  'x2',
  'y1',
  'y2',
  'width',
  'height',
  'points',
  'fill',
])
function parseAttributes(source, allowed) {
  const result = {}
  const rest = source.replace(/([\w-]+)="([^"]*)"/g, (_, name, value) => {
    assert.ok(allowed.has(name), `Unsupported icon attribute: ${name}`)
    assert.ok(!(name in result), `Duplicate icon attribute: ${name}`)
    result[name] = value
    return ''
  })
  assert.equal(rest.trim(), '', 'Unsupported icon attribute syntax')
  return result
}

export function parseIcon(name, svg) {
  const root = svg.trim().match(/^<svg\s+([^>]+)>([\s\S]*)<\/svg>$/)
  assert.ok(root, `${name}: expected one SVG root`)
  const attrs = parseAttributes(
    root[1],
    new Set([
      'xmlns',
      'width',
      'height',
      'viewBox',
      'fill',
      'stroke',
      'stroke-width',
      'stroke-linecap',
      'stroke-linejoin',
    ]),
  )
  assert.equal(attrs.viewBox, '0 0 24 24')
  assert.equal(attrs.fill, 'none')
  assert.equal(attrs.stroke, 'currentColor')
  const nodes = []
  const remaining = root[2].replace(
    /<([a-z]+)\s+([^<>]*?)\s*\/>/g,
    (_, tag, raw) => {
      assert.ok(tags.has(tag), `${name}: unsupported element ${tag}`)
      const values = parseAttributes(raw, attributes)
      for (const [key, value] of Object.entries(values)) {
        assert.ok(
          key === 'fill'
            ? ['none', 'currentColor'].includes(value)
            : /^[a-zA-Z0-9.,+\s-]+$/.test(value),
          `${name}: unsupported value for ${key}`,
        )
      }
      nodes.push([tag, values])
      return ''
    },
  )
  assert.equal(remaining.trim(), '', `${name}: unsupported SVG content`)
  assert.ok(nodes.length, `${name}: empty icon`)
  return { name, viewBox: attrs.viewBox, nodes }
}

const hash = (value) => createHash('sha256').update(value).digest('hex')
async function main() {
  const base = new URL('../packages/components/src/', import.meta.url)
  const originals = JSON.parse(
    await readFile(new URL('vendor/icons/upstream.json', base), 'utf8'),
  )
  const manifestUrl = new URL('vendor/icons/provenance.json', base)
  const manifest = JSON.parse(await readFile(manifestUrl, 'utf8'))
  assert.deepEqual(Object.keys(originals), Object.keys(manifest.icons))
  assert.equal(
    hash(await readFile(new URL('vendor/icons/LICENSE', base))),
    manifest.licenseSha256,
  )
  const names = new Set()
  let source =
    '// Generated by scripts/icons.mjs from pinned SVG artwork.\n// See ../vendor/icons/LICENSE for ISC and MIT notices.\nimport type { IconDefinition } from "./types"\nexport type { IconDefinition } from "./types"\n'
  for (const [name, svg] of Object.entries(originals)) {
    assert.equal(
      hash(svg),
      manifest.icons[name],
      `${name}: upstream hash mismatch`,
    )
    const exported =
      'icon' +
      name
        .split('-')
        .map((part) => part[0].toUpperCase() + part.slice(1))
        .join('')
    assert.ok(!names.has(exported), `${name}: duplicate export`)
    names.add(exported)
    source += `export const ${exported}: IconDefinition = ${JSON.stringify(parseIcon(name, svg))}\n`
  }
  source = await format(source, {
    parser: 'typescript',
    ...JSON.parse(
      await readFile(new URL('../.prettierrc.json', import.meta.url), 'utf8'),
    ),
  })
  const output = new URL('icons/index.ts', base)
  if (process.argv.includes('--check')) {
    assert.equal(
      await readFile(output, 'utf8'),
      source,
      'Generated icons are stale',
    )
    assert.equal(manifest.generatedSha256, hash(source))
    assert.equal(
      manifest.generatorSha256,
      hash(await readFile(new URL(import.meta.url))),
    )
  } else {
    await writeFile(new URL('icons/index.ts.tmp', base), source)
    await rename(new URL('icons/index.ts.tmp', base), output)
    manifest.generatedSha256 = hash(source)
    manifest.generatorSha256 = hash(await readFile(new URL(import.meta.url)))
    await writeFile(manifestUrl, JSON.stringify(manifest, null, 2) + '\n')
  }
  console.log(
    `Icons: ${names.size} pinned definitions ${process.argv.includes('--check') ? 'verified' : 'generated'}`,
  )
}
if (
  process.argv[1] &&
  resolve(process.argv[1]) === fileURLToPath(import.meta.url)
)
  await main()
